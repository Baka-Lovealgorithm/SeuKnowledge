-- ============================================================================
-- SeuKnowledge 迁移脚本 v5：Agent 记忆策略改为「近窗轮数 + 压缩间隔轮数」
-- ----------------------------------------------------------------------------
-- 适用：已有 v4 数据库，升级到 v5（schema.sql 已含下列列，全新部署无需执行本脚本）
-- 内容：kb_agent 增 2 列 recent_rounds / summary_interval_rounds
-- 特性：全部可空、无默认值、无索引、无外键、**不回填** —— 存量行与老功能零影响
-- 注意：应用使用 JPA ddl-auto:update，只要用新版启动过一次，列就已自动补齐，
--       此时再执行本脚本会报 Duplicate column name（无害，跳过即可）
-- 执行：mysql -u root -p seuknowledge < migrate_v5_agent_memory_policy.sql
-- 回滚：列可留（老代码按名取列，不认得的列不影响读写）；确需清理见下方「回滚」段
-- ============================================================================

ALTER TABLE kb_agent
    ADD COLUMN recent_rounds integer NULL,
    ADD COLUMN summary_interval_rounds integer NULL;

-- ============================================================================
-- 列语义（与前端「Agent 配置」页的两个输入项一一对应）
-- ----------------------------------------------------------------------------
--   recent_rounds            ：注入 prompt 的最近对话原文轮数（每轮 = user + assistant 两条）。
--                              代码侧 clamp 到 1 ~ (qa.message-window / 2)；NULL = 用默认 3。
--   summary_interval_rounds  ：滚动摘要的压缩间隔轮数，**必须 ≤ recent_rounds**（否则两次压缩
--                              之间积压的消息会既不在摘要里、也不在近窗里 = 真丢失）。
--                              服务端写入时校验、读取时 clamp；NULL = 用默认 3。
--
-- memory_window 保留不动（遗留列）：旧「记忆窗口条数」语义已废弃，代码不再映射该列；
--                   存量值（多为 20）无保留价值，留列仅为支持回滚，请勿复用。
--
-- 全局配置 seuknowledge.qa.message-window（默认 20 条，env KB_QA_MESSAGE_WINDOW）保持不变：
--   它是历史取数上限与 Redis 缓存容量基准，不在 Agent 页暴露、不可按库调节。
--
-- 升级后的行为：
--   1. 存量 Agent 行的两新列为 NULL → 按默认 3/3 生效（与改造前实际注入量一致，行为无跳变）；
--   2. 旧页面填过的 memory_window 值不再有任何效果；
--   3. 读取接口 /api/kb/{kbId}/agent 回显的是「生效值」而非 NULL，前端无需判空。
-- ============================================================================

